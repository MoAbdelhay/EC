// Builds www/ for the app from the calculator source on Google Drive.
//
// The calculator is edited in one place only:
//   G:\My Drive\Benchmarkguides\Calculation Sheets BG\MEP Calculator\index.html
// (override with the CALC_SOURCE environment variable).
//
// This script wraps that page in a proper app shell (doctype, viewport with safe areas,
// fonts bundled for offline use) and writes www/index.html. Fonts are downloaded once
// from Google Fonts into static/fonts/ and reused after that (commit them).
import { readFile, writeFile, mkdir, cp, access } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DRIVE_SOURCE = process.env.CALC_SOURCE ||
  "G:/My Drive/Benchmarkguides/Calculation Sheets BG/MEP Calculator/index.html";
// A copy is kept in the repo (src/calculator.html) so cloud builds (GitHub Actions, no Drive) work.
// It is refreshed from Drive whenever the Drive file is reachable.
const REPO_COPY = join(ROOT, "src", "calculator.html");
const FONTS_DIR = join(ROOT, "static", "fonts");
const FONTS_CSS_URL = "https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500" +
  "&family=Saira:wdth,wght@100..125,400..700" +
  "&family=Source+Serif+4:ital,opsz,wght@0,8..60,400..600;1,8..60,400" +
  "&family=IBM+Plex+Sans+Arabic:wght@400;500;600;700" +
  "&family=Noto+Naskh+Arabic:wght@400;500;600&display=swap";
const KEEP_SUBSETS = new Set(["latin", "latin-ext", "arabic"]);
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";

const exists = (p) => access(p).then(() => true, () => false);

async function fetchFonts() {
  const cssOut = join(FONTS_DIR, "fonts.css");
  if (await exists(cssOut)) return;
  await mkdir(FONTS_DIR, { recursive: true });
  const css = await (await fetch(FONTS_CSS_URL, { headers: { "User-Agent": UA } })).text();
  const blocks = css.split(/(?=\/\* [a-z-]+ \*\/)/).filter((b) => {
    const m = b.match(/^\/\* ([a-z-]+) \*\//);
    return m && KEEP_SUBSETS.has(m[1]);
  });
  let n = 0, out = "/* Bundled from Google Fonts (OFL). Generated by scripts/build-web.mjs. */\n";
  for (const block of blocks) {
    let local = block;
    for (const [, url] of block.matchAll(/url\((https:[^)]+\.woff2)\)/g)) {
      const name = `f${String(++n).padStart(3, "0")}.woff2`;
      const buf = Buffer.from(await (await fetch(url, { headers: { "User-Agent": UA } })).arrayBuffer());
      await writeFile(join(FONTS_DIR, name), buf);
      local = local.replace(url, name);
    }
    out += local;
  }
  await writeFile(cssOut, out);
  console.log(`fonts: ${n} files saved to static/fonts`);
}

function appShell(src) {
  // Keep everything from the page-shell <style> onwards (calculator element, its CSS template and code);
  // drop the source page's <title>, artifact meta and remote font links.
  const body = src.slice(src.indexOf("<style>"));
  return `<!doctype html>
<html lang="ar" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,viewport-fit=cover">
<meta name="theme-color" content="#EDEFEA">
<meta name="format-detection" content="telephone=no">
<title>Engineer's Calculator</title>
<link rel="stylesheet" href="fonts/fonts.css">
<style>html,body{margin:0;-webkit-tap-highlight-color:transparent;overscroll-behavior-y:none}</style>
</head>
<body>
${body}
</body>
</html>
`;
}

async function main() {
  await fetchFonts();
  let SOURCE = REPO_COPY;
  if (await exists(DRIVE_SOURCE)) {
    await mkdir(dirname(REPO_COPY), { recursive: true });
    await cp(DRIVE_SOURCE, REPO_COPY);
    SOURCE = DRIVE_SOURCE;
  }
  const src = await readFile(SOURCE, "utf8");
  if (!src.includes("<bg-calculator") || !src.includes('id="bgc-js"')) {
    throw new Error(`${SOURCE} does not look like the calculator source`);
  }
  const www = join(ROOT, "www");
  await mkdir(www, { recursive: true });
  await cp(FONTS_DIR, join(www, "fonts"), { recursive: true });
  await writeFile(join(www, "index.html"), appShell(src));
  console.log(`www/index.html built from ${SOURCE}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
